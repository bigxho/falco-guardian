/*
 * loader.c
 *
 * Userspace program that:
 *  1. Loads and attaches the capture.bpf.c eBPF program (XDP) to an interface.
 *  2. Reads events from the BPF ring buffer.
 *  3. Serializes them as JSON (one line per event) and broadcasts them to all
 *     clients connected to a Unix socket (consumed by python/core/capture_client.py).
 *
 * Usage: sudo ./build/loader <interface>   (for example, eth0)
 */
#define _GNU_SOURCE
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <signal.h>
#include <unistd.h>
#include <errno.h>
#include <pthread.h>
#include <sys/socket.h>
#include <sys/stat.h>
#include <sys/un.h>
#include <arpa/inet.h>
#include <net/if.h>
#include <bpf/libbpf.h>
#include <bpf/bpf.h>
#include "common.h"
#include "capture.skel.h" /* generated by the Makefile with `bpftool gen skeleton` */

#define MAX_CLIENTS 16

static volatile sig_atomic_t stop;
static int client_fds[MAX_CLIENTS];
static pthread_mutex_t clients_lock = PTHREAD_MUTEX_INITIALIZER;

static void handle_signal(int sig)
{
    (void)sig;
    stop = 1;
}

/* Send one JSON line to all connected clients and remove disconnected clients. */
static void broadcast(const char *line, size_t len)
{
    pthread_mutex_lock(&clients_lock);
    for (int i = 0; i < MAX_CLIENTS; i++) {
        if (client_fds[i] >= 0) {
            ssize_t w = write(client_fds[i], line, len);
            if (w < 0) {
                close(client_fds[i]);
                client_fds[i] = -1;
            }
        }
    }
    pthread_mutex_unlock(&clients_lock);
}

static void *accept_loop(void *arg)
{
    int srv_fd = *(int *)arg;
    while (!stop) {
        int cfd = accept(srv_fd, NULL, NULL);
        if (cfd < 0) {
            if (errno == EINTR) continue;
            break;
        }
        pthread_mutex_lock(&clients_lock);
        int placed = 0;
        for (int i = 0; i < MAX_CLIENTS; i++) {
            if (client_fds[i] < 0) {
                client_fds[i] = cfd;
                placed = 1;
                break;
            }
        }
        pthread_mutex_unlock(&clients_lock);
        if (!placed) {
            fprintf(stderr, "[falco-ebpf] too many connected clients; rejecting new connection\n");
            close(cfd);
        }
    }
    return NULL;
}

static int setup_socket(void)
{
    /* Ensure the socket directory exists. systemd normally creates it with
     * RuntimeDirectory=falco-guardian; this is only a fallback. */
    mkdir("/run/falco-guardian", 0770);
    unlink(FALCO_SOCK_PATH);

    int fd = socket(AF_UNIX, SOCK_STREAM, 0);
    if (fd < 0) { perror("socket"); return -1; }

    struct sockaddr_un addr;
    memset(&addr, 0, sizeof(addr));
    addr.sun_family = AF_UNIX;
    strncpy(addr.sun_path, FALCO_SOCK_PATH, sizeof(addr.sun_path) - 1);

    if (bind(fd, (struct sockaddr *)&addr, sizeof(addr)) < 0) {
        perror("bind"); close(fd); return -1;
    }
    chmod(FALCO_SOCK_PATH, 0660);
    if (listen(fd, 8) < 0) { perror("listen"); close(fd); return -1; }
    return fd;
}

static inline void ip_to_str(__u32 ip_be, char *buf, size_t buflen)
{
    struct in_addr a;
    a.s_addr = ip_be;
    inet_ntop(AF_INET, &a, buf, buflen);
}

static int handle_event(void *ctx, void *data, size_t data_sz)
{
    (void)ctx; (void)data_sz;
    const struct pkt_event *e = data;
    char src[INET_ADDRSTRLEN], dst[INET_ADDRSTRLEN];
    ip_to_str(e->src_ip, src, sizeof(src));
    ip_to_str(e->dst_ip, dst, sizeof(dst));

    char line[256];
    int n = snprintf(line, sizeof(line),
        "{\"ts_ns\":%llu,\"src_ip\":\"%s\",\"dst_ip\":\"%s\",\"src_port\":%u,"
        "\"dst_port\":%u,\"protocol\":%u,\"len\":%u,\"tcp_flags\":%u}\n",
        (unsigned long long)e->timestamp_ns, src, dst,
        (unsigned)e->src_port, (unsigned)e->dst_port,
        (unsigned)e->protocol, (unsigned)e->pkt_len, (unsigned)e->tcp_flags);

    if (n > 0)
        broadcast(line, (size_t)n);
    return 0;
}

int main(int argc, char **argv)
{
    if (argc < 2) {
        fprintf(stderr, "Usage: %s <network interface>\n", argv[0]);
        return 1;
    }
    const char *ifname = argv[1];
    int ifindex = if_nametoindex(ifname);
    if (!ifindex) {
        perror("if_nametoindex");
        return 1;
    }

    for (int i = 0; i < MAX_CLIENTS; i++)
        client_fds[i] = -1;

    signal(SIGINT, handle_signal);
    signal(SIGTERM, handle_signal);

    struct capture_bpf *skel = capture_bpf__open_and_load();
    if (!skel) {
        fprintf(stderr, "[falco-ebpf] unable to load the eBPF program\n");
        return 1;
    }

    int prog_fd = bpf_program__fd(skel->progs.xdp_capture);
    if (bpf_xdp_attach(ifindex, prog_fd, 0, NULL) < 0) {
        fprintf(stderr, "[falco-ebpf] unable to attach XDP to %s\n", ifname);
        capture_bpf__destroy(skel);
        return 1;
    }

    int srv_fd = setup_socket();
    if (srv_fd < 0) {
        bpf_xdp_detach(ifindex, 0, NULL);
        capture_bpf__destroy(skel);
        return 1;
    }

    pthread_t accept_tid;
    pthread_create(&accept_tid, NULL, accept_loop, &srv_fd);

    struct ring_buffer *rb = ring_buffer__new(
        bpf_map__fd(skel->maps.events), handle_event, NULL, NULL);
    if (!rb) {
        fprintf(stderr, "[falco-ebpf] unable to create the ring buffer\n");
        goto cleanup;
    }

    fprintf(stderr, "[falco-ebpf] capture active on %s, event socket: %s\n",
            ifname, FALCO_SOCK_PATH);

    while (!stop) {
        int err = ring_buffer__poll(rb, 200 /* ms */);
        if (err < 0 && err != -EINTR) {
            fprintf(stderr, "[falco-ebpf] ring_buffer__poll error: %d\n", err);
            break;
        }
    }

    ring_buffer__free(rb);

cleanup:
    fprintf(stderr, "[falco-ebpf] shutting down...\n");
    bpf_xdp_detach(ifindex, 0, NULL);
    close(srv_fd);
    unlink(FALCO_SOCK_PATH);
    capture_bpf__destroy(skel);
    return 0;
}
